// Computes expected outputs from references and emits question-bank/q_other.js (literal values).
// Usage (repo root): node question-bank/gen/build.js
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { sqlAuthor, nosqlAuthor } from './author_data.js';
import { uiAuthor, mcqAuthor } from './author_ui_mcq.js';
import { sqlRun, nosqlRun } from './lib.js';

const MARKS = { easy: 10, medium: 20, hard: 30 };
const MINS = { sql: { easy: 3, medium: 6, hard: 9 }, nosql: { easy: 3, medium: 6, hard: 9 }, ui: { easy: 4, medium: 7, hard: 10 } };
const MCQ_MARKS = { easy: 5, medium: 10, hard: 15 };
const MCQ_MINS = { easy: 1, medium: 2, hard: 3 };

const sql = [];
for (const q of sqlAuthor) {
  const tests = [];
  for (const d of q.datasets) {
    const { columns, rows } = await sqlRun(q.schema_sql, d.sql, q.reference_sql);
    tests.push({ setup_sql: d.sql, expected: { columns, rows }, hidden: d.h });
  }
  sql.push({ subject: 'SQL', type: 'sql', difficulty: q.difficulty, title: q.title, statement: q.statement, marks: MARKS[q.difficulty], time_mins: MINS.sql[q.difficulty], tags: q.tags,
    config: { schema_sql: q.schema_sql, ordered: q.ordered, constraints: q.constraints }, tests, reference: { sql: q.reference_sql } });
}

const nosql = nosqlAuthor.map((q) => ({
  subject: 'NoSQL (MongoDB)', type: 'nosql', difficulty: q.difficulty, title: q.title, statement: q.statement, marks: MARKS[q.difficulty], time_mins: MINS.nosql[q.difficulty], tags: q.tags,
  config: { mode: q.mode, collection: q.collection, ordered: q.ordered, constraints: q.constraints },
  tests: q.datasets.map((d) => ({ data: d.data, expected: nosqlRun(q.mode, q.reference, d.data), hidden: d.h })),
  reference: q.reference,
}));

const ui = uiAuthor.map((q) => ({
  subject: 'Quick Dev (UI Debug)', type: 'ui', difficulty: q.difficulty, title: q.title, statement: q.statement, marks: MARKS[q.difficulty], time_mins: MINS.ui[q.difficulty], tags: q.tags,
  config: { files: q.files, editable: q.editable || Object.keys(q.files), constraints: q.constraints },
  tests: q.tests,
  reference: { files: { ...q.files, ...q.fixed } },
}));

const mcq = mcqAuthor.map((q) => ({
  subject: 'AI/ML', type: 'mcq', difficulty: q.difficulty, title: q.title, statement: q.statement, marks: MCQ_MARKS[q.difficulty], time_mins: MCQ_MINS[q.difficulty], tags: q.tags,
  config: { options: q.options, multiple: !!q.multiple, correct: q.correct, scenario: q.scenario }, tests: [],
}));

const out = `// AUTO-GENERATED by question-bank/gen/build.js - do not edit by hand (edit gen/author_*.js and re-run the build).
// \`reference\` fields are for validation only: the seed script / API must NOT send them to candidates.
export const sql = ${JSON.stringify(sql, null, 1)};

export const nosql = ${JSON.stringify(nosql, null, 1)};

export const ui = ${JSON.stringify(ui, null, 1)};

export const mcq = ${JSON.stringify(mcq, null, 1)};
`;
writeFileSync(fileURLToPath(new URL('../q_other.js', import.meta.url)), out);
console.log(`wrote q_other.js: sql=${sql.length} nosql=${nosql.length} ui=${ui.length} mcq=${mcq.length}`);
