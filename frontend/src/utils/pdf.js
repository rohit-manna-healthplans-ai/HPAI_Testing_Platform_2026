import { jsPDF } from 'jspdf';
import { fmtDate, fmtDay, num, pct } from './format.js';

const NAVY = [23, 63, 89];
const BLUE = [31, 102, 136];
const GREEN = [11, 211, 122];
const MUTED = [113, 136, 149];
const SKY = [162, 207, 226];

function loadLogo() {
  return new Promise((resolve) => {
    const img = new Image();
    img.onload = () => {
      try {
        const c = document.createElement('canvas');
        c.width = img.naturalWidth; c.height = img.naturalHeight;
        c.getContext('2d').drawImage(img, 0, 0);
        resolve({ data: c.toDataURL('image/png'), w: img.naturalWidth, h: img.naturalHeight });
      } catch { resolve(null); }
    };
    img.onerror = () => resolve(null);
    img.src = '/logo.png';
  });
}

function placeLogo(doc, logo, x, y, size) {
  if (!logo) return;
  const ratio = logo.w / logo.h;
  const w = ratio >= 1 ? size : size * ratio;
  const h = ratio >= 1 ? size / ratio : size;
  doc.addImage(logo.data, 'PNG', x, y, w, h);
}

const safeName = (s) => String(s || 'candidate').replace(/[^\w]+/g, '_').replace(/^_|_$/g, '');

/** result: shape of GET /candidate/attempts/:id/result */
export async function downloadResultPDF(result) {
  const logo = await loadLogo();
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();

  doc.setFillColor(...NAVY); doc.rect(0, 0, W, 38, 'F');
  doc.setFillColor(...GREEN); doc.rect(0, 38, W, 2, 'F');
  placeLogo(doc, logo, 14, 7, 24);
  doc.setTextColor(255, 255, 255); doc.setFont('helvetica', 'bold'); doc.setFontSize(20);
  doc.text('HPAI Testing Assessment', 44, 18);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(11); doc.setTextColor(...SKY);
  doc.text('Candidate Result Report', 44, 26);

  let y = 56;
  doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(16);
  doc.text(result.candidate_name || 'Candidate', 16, y);
  y += 8;
  doc.setFont('helvetica', 'normal'); doc.setFontSize(10.5); doc.setTextColor(...MUTED);
  doc.text(`Assessment: ${result.session_name || '—'}`, 16, y); y += 6;
  doc.text(`Submitted: ${fmtDate(result.submitted_at)}`, 16, y); y += 6;
  if (result.certificate_code) { doc.text(`Certificate ID: ${result.certificate_code}`, 16, y); y += 6; }

  y += 6;
  doc.setDrawColor(...SKY); doc.setFillColor(240, 248, 251);
  doc.roundedRect(16, y, W - 32, 34, 4, 4, 'FD');
  doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(32);
  doc.text(`${num(result.total_score)} / ${num(result.max_score)}`, 26, y + 21);
  doc.setFontSize(12); doc.setTextColor(...BLUE);
  doc.text(`${num(result.percentage)}%`, W - 28, y + 15, { align: 'right' });
  doc.setFontSize(11); doc.text(result.grade || '', W - 28, y + 24, { align: 'right' });
  y += 48;

  doc.setTextColor(...NAVY); doc.setFont('helvetica', 'bold'); doc.setFontSize(13);
  doc.text('Marks by subject', 16, y); y += 6;
  doc.setFontSize(10);
  doc.setFillColor(...NAVY); doc.rect(16, y, W - 32, 8, 'F');
  doc.setTextColor(255, 255, 255);
  doc.text('Subject', 20, y + 5.5); doc.text('Score', W - 70, y + 5.5); doc.text('Max', W - 50, y + 5.5); doc.text('%', W - 26, y + 5.5, { align: 'right' });
  y += 8;
  doc.setFont('helvetica', 'normal');
  (result.by_subject || []).forEach((s, i) => {
    if (i % 2 === 0) { doc.setFillColor(246, 250, 252); doc.rect(16, y, W - 32, 8, 'F'); }
    doc.setTextColor(...NAVY);
    doc.text(String(s.subject), 20, y + 5.5);
    doc.text(String(num(s.score)), W - 70, y + 5.5);
    doc.text(String(num(s.max)), W - 50, y + 5.5);
    doc.text(`${pct(s.score, s.max)}%`, W - 26, y + 5.5, { align: 'right' });
    y += 8;
  });
  doc.setFontSize(8.5); doc.setTextColor(...MUTED);
  doc.text('Generated by the HPAI Assessment Platform. Automated evaluation.', W / 2, 287, { align: 'center' });
  doc.save(`HPAI_Result_${safeName(result.candidate_name)}.pdf`);
}

export async function downloadCertificate(result) {
  const logo = await loadLogo();
  const doc = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a4' });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();

  doc.setFillColor(252, 254, 255); doc.rect(0, 0, W, H, 'F');
  doc.setDrawColor(...NAVY); doc.setLineWidth(2.2); doc.rect(8, 8, W - 16, H - 16);
  doc.setDrawColor(...GREEN); doc.setLineWidth(0.8); doc.rect(12, 12, W - 24, H - 24);
  doc.setDrawColor(...SKY); doc.setLineWidth(0.3); doc.rect(15, 15, W - 30, H - 30);
  // corner accents
  doc.setFillColor(...NAVY);
  [[8, 8], [W - 8, 8], [8, H - 8], [W - 8, H - 8]].forEach(([x, y]) => doc.circle(x, y, 3.2, 'F'));
  doc.setFillColor(...GREEN);
  [[8, 8], [W - 8, 8], [8, H - 8], [W - 8, H - 8]].forEach(([x, y]) => doc.circle(x, y, 1.4, 'F'));

  placeLogo(doc, logo, W / 2 - 13, 20, 26);

  doc.setTextColor(...NAVY); doc.setFont('times', 'bold'); doc.setFontSize(34);
  doc.text('Certificate of Assessment', W / 2, 62, { align: 'center' });
  doc.setDrawColor(...GREEN); doc.setLineWidth(1); doc.line(W / 2 - 38, 67, W / 2 + 38, 67);

  doc.setFont('helvetica', 'normal'); doc.setFontSize(13); doc.setTextColor(...MUTED);
  doc.text('This is to certify that', W / 2, 82, { align: 'center' });

  doc.setFont('times', 'bolditalic'); doc.setFontSize(34); doc.setTextColor(...BLUE);
  doc.text(result.candidate_name || 'Candidate', W / 2, 98, { align: 'center' });
  doc.setDrawColor(...SKY); doc.setLineWidth(0.4); doc.line(W / 2 - 70, 102, W / 2 + 70, 102);

  doc.setFont('helvetica', 'normal'); doc.setFontSize(13); doc.setTextColor(...NAVY);
  doc.text('has successfully completed the', W / 2, 114, { align: 'center' });
  doc.setFont('helvetica', 'bold'); doc.setFontSize(18);
  doc.text('HPAI Testing Assessment', W / 2, 124, { align: 'center' });

  doc.setFont('helvetica', 'normal'); doc.setFontSize(12); doc.setTextColor(...MUTED);
  const line = `with a score of ${num(result.total_score)} out of ${num(result.max_score)} (${num(result.percentage)}%) — ${result.grade || ''}`;
  doc.text(line, W / 2, 135, { align: 'center' });

  const footY = H - 34;
  doc.setDrawColor(...NAVY); doc.setLineWidth(0.4);
  doc.line(30, footY, 90, footY); doc.line(W - 90, footY, W - 30, footY);
  doc.setFontSize(10); doc.setTextColor(...NAVY);
  doc.text(fmtDay(result.submitted_at), 60, footY + 6, { align: 'center' });
  doc.setTextColor(...MUTED); doc.text('Date of assessment', 60, footY + 11, { align: 'center' });
  doc.setTextColor(...NAVY); doc.text('HPAI · Healthplans.ai', W - 60, footY + 6, { align: 'center' });
  doc.setTextColor(...MUTED); doc.text('Issued by', W - 60, footY + 11, { align: 'center' });

  if (result.certificate_code) {
    doc.setFont('helvetica', 'bold'); doc.setFontSize(10); doc.setTextColor(...NAVY);
    doc.text(`Certificate ID: ${result.certificate_code}`, W / 2, footY - 2, { align: 'center' });
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8.5); doc.setTextColor(...MUTED);
    doc.text(`Verify at ${window.location.origin}/verify/${result.certificate_code}`, W / 2, footY + 4, { align: 'center' });
  }
  doc.save(`HPAI_Certificate_${safeName(result.candidate_name)}.pdf`);
}
